const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const svc=fs.readFileSync(path.join(root,'services/event-ai.service.js'),'utf8');
const paths=fs.readFileSync(path.join(root,'server/paths.js'),'utf8');
const hardlock=fs.readFileSync(path.join(root,'public/app/features/v4-1-exp-version-hardlock.js'),'utf8');
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const checks=[];
const ok=(name,cond)=>checks.push([name,!!cond]);
const block=(start,end)=>{const a=svc.indexOf(start),b=svc.indexOf(end,a);return a>=0&&b>a?svc.slice(a,b):''};
const decision=block('async function v6GeminiDecision(', '\n\nasync function runZuzuV6Agent');
const context=block('function v6ContextPacket(', '\nfunction v6Rows(');
ok('schema v6_1 existe',/function v61OutputContractSchema\(\)/.test(svc));
ok('schema exige 4 bloques raíz',/required:\['thread_mutation','execution_intent','required_materials','assistant_response'\]/.test(svc));
ok('decision usa responseSchema',/responseSchema:schema/.test(decision));
ok('decision usa Structured Output, no plain text',/plainTextResponse:false/.test(decision));
ok('decision no envía tools',/tools:\[\]/.test(decision));
ok('decision no usa v6StateTools',!decision.includes('v6StateTools'));
ok('decision no tiene reintento estructural',!decision.includes('REINTENTO')&&!decision.includes('contract_retry'));
ok('decode parsea JSON estructurado y valida CE',/JSON\.parse\(raw\)/.test(svc)&&/return v6ValidateContract\(parsed\)/.test(svc));
ok('system prompt exige JSON sin function calling',/SALIDA ESTRUCTURADA: devuelve única y exclusivamente un objeto JSON/.test(svc));
ok('context packet de v6.0.10 se conserva',/recent_dialogue/.test(context)&&/conversation_state/.test(context)&&/resolved_materials/.test(context)&&/ontology:v6Ontology\(\)/.test(context));
ok('ruta sigue sin fallback cognitivo',/FALLO SIN FALLBACK/.test(svc)&&/No he recurrido a ningún motor anterior/.test(svc));
ok('versión backend v6_1-exp',/APP_VERSION_LABEL = 'v6_1-exp'/.test(paths));
ok('versión cliente v6_1-exp',/v6_1-exp/.test(hardlock)&&/v6_1-exp/.test(html));
ok('sin versión activa v6.0.10 en core',!svc.includes("version:'v6.0.10_exp'")&&!hardlock.includes('v6.0.10_exp')&&!html.includes('v6.0.10_exp'));
const bad=checks.filter(x=>!x[1]);
for(const [n,v] of checks)console.log(`${v?'OK':'KO'}  ${n}`);
console.log(`\n${checks.length-bad.length}/${checks.length} OK`);
if(bad.length)process.exit(1);
